using System;

namespace XrmFramework
{
    /// <summary>
    /// Centralizes the rules stating which types the dependency container is allowed to inject
    /// as parameters of a plugin step method or of a custom workflow activity action.
    /// </summary>
    internal static class InjectionRules
    {
        /// <summary>
        /// Returns <c>true</c> when <paramref name="type"/> is an interface the dependency container
        /// is able to provide: an <see cref="IService"/> generated by the framework, or any
        /// <see cref="IXrmFrameworkService"/> — built-in ones such as <see cref="IDateTimeProvider"/>
        /// as well as the custom services the consuming project registers in
        /// <c>InternalDependencyProvider.RegisterCustomService</c>.
        /// </summary>
        /// <param name="type">The declared parameter type.</param>
        public static bool IsInjectableService(Type type)
            => type != null
               && type.IsInterface
               && (typeof(IService).IsAssignableFrom(type)
                   || typeof(IXrmFrameworkService).IsAssignableFrom(type));
    }
}
